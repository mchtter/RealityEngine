/** Raw OSM element as stored in fixtures (Overpass `out geom`, compacted). */
export interface OsmElement {
  type: 'node' | 'way' | 'relation';
  id: number;
  tags: Record<string, string>;
  lon?: number;
  lat?: number;
  nodes?: number[];
  geometry?: [number, number][];
  members?: { ref: number; role: string; geometry: [number, number][] }[];
}

/** Terrain height grid in geographic coordinates, row 0 = north, pixel centres. */
export interface GeoTerrainGrid {
  source: string;
  west: number;
  east: number;
  north: number;
  south: number;
  cols: number;
  rows: number;
  heights: number[];
}

/** GeoJSON geometry (EPSG:4326) of a source-store feature. */
export interface SourceGeometry {
  type: 'Point' | 'LineString' | 'MultiLineString' | 'Polygon' | 'MultiPolygon';
  coordinates: unknown;
}

/** A canonical feature from the source store (OSM import, MAKS, platform layer…). */
export interface SourceFeatureInput {
  /** Stable identity, e.g. "osm:w123", "maks:4711". */
  ref: string;
  /** Short source name shown to users ("osm", "maks", …). */
  source: string;
  /** Higher wins: a building overrides lower-priority buildings it overlaps. */
  priority?: number;
  /**
   * The source is the complete building register where it has data (e.g. the
   * municipality's MAKS table): around its buildings no other source's
   * building and no procedural infill is placed.
   */
  authoritative?: boolean;
  /** `line`: a landform line (`natural=cliff` / `coastline`) that shapes the terrain. */
  kind: 'building' | 'road' | 'area' | 'point' | 'line';
  geometry: SourceGeometry;
  tags: Record<string, string | number>;
}

/** Compile target: a 1 km UTM tile (see tiles.ts). */
export interface TileFrameInput {
  zone: number;
  originE: number;
  originN: number;
  size: number;
  margin: number;
}

export interface CitySource {
  name: string;
  /** [west, south, east, north] — the area to compile when no `frame` is given. */
  bbox: [number, number, number, number];
  attribution: string[];
  osm?: OsmElement[];
  features?: SourceFeatureInput[];
  terrain?: GeoTerrainGrid;
  /** Compile exactly this tile (model coords = UTM − origin); `bbox` is then ignored. */
  frame?: TileFrameInput;
}

