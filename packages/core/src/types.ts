/**
 * City model contract produced by `compileCity` and consumed by renderers.
 *
 * Coordinates are local metres on a tangent plane around `origin`:
 * x = east, y = north, z = up (terrain / building heights). Renderers map
 * this to their own axes (three.js: x, z = -y, y = up).
 */

export type Vec2 = [number, number];
export type Vec3 = [number, number, number];

/** Polygon with an outer ring (CCW) and optional holes (CW). Rings are open (last != first). */
export interface Polygon {
  outer: Vec2[];
  holes: Vec2[][];
}

/**
 * Where a value came from:
 * - `observed`: present in the source data
 * - `inferred`: derived by a rule from observed evidence (e.g. crossing at a signalised junction)
 * - `synthetic`: generated only so the scene looks complete (decoration, block infill)
 * - `suggested`: generated by an analysis rule and meant as a planning hint (e.g. missing bus stop)
 */
export type Provenance = 'observed' | 'inferred' | 'synthetic' | 'suggested';

