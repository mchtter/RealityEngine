export interface Bridge {
  id: string;
  roadId: string;
  /** Deck centreline with deck-top heights. */
  path: Vec3[];
  /** Whole deck width (carriageway + walkways). */
  width: number;
  /** Carriageway width, lanes and direction, for the deck's lane markings. */
  carriageway: number;
  lanes: number;
  oneway: boolean;
  /** Edge lines on fast roads (motorway / trunk / primary), as on the ground. */
  edgeLines: boolean;
  /** Piers where the deck stands clear of the ground: base on the terrain, top under the deck. */
  piers: {
    at: Vec2;
    dir: Vec2;
    base: number;
    top: number;
    /** Lateral offsets of its columns from `at` (one under a narrow deck, two under a wide one). */
    columns: number[];
  }[];
}

/** Open trench of an underpass approach: retaining walls along both sides. */
export interface Cutting {
  id: string;
  /** Tunnel road the ramp leads into. */
  roadId: string;
  /** Ramp centreline from the portal outwards, with (flat) trench-floor heights. */
  path: Vec3[];
  /** Distance between the two retaining walls. */
  width: number;
  /** The ramp road: drawn by the trench itself (ground surfaces stop at its walls). */
  carriageway: number;
  lanes: number;
  oneway: boolean;
  edgeLines: boolean;
  /**
   * Retaining wall top per path point, left / right: the street level just
   * beyond the wall plus a parapet. Set by the compiler, which also keeps the
   * ground beside the wall below it (in every tile the trench reaches).
   */
  rimL?: number[];
  rimR?: number[];
}

/** Concrete headwall around a tunnel mouth. */
export interface Portal {
  id: string;
  roadId: string;
  /** Road level at the mouth (centre). */
  at: Vec3;
  /** Unit vector pointing out of the tunnel. */
  facing: Vec2;
  /** Headwall width. */
  width: number;
  /** Clear opening: tube width and height. */
  opening: number;
  height: number;
  /** Headwall height above road level. */
  wall: number;
  /** Mouth of a tunnel into a hill (an underpass's mouth faces its trench). */
  hill?: boolean;
}

/**
 * Where underpass trenches and tunnel mouths cut the ground. The terrain grid
 * keeps the natural heights and is not drawn inside either footprint: inside
 * `trenches` the ground is the trench floor, inside `lids` the cut-and-cover
 * lid over the shallow first metres of a tube. Both surfaces are the terrain
 * grid with the listed nodes (model x, y, height) changed.
 */
export interface TerrainCut {
  trenches: Polygon[];
  lids: Polygon[];
  floor: Vec3[];
  lid: Vec3[];
}

/** Drivable tunnel tube: road, walkways, lit walls and ceiling. */
export interface Tunnel {
  id: string;
  roadId: string;
  name?: string;
  /** Centreline with road (floor) heights. */
  path: Vec3[];
  /** Wall to wall. */
  width: number;
  /** Clear height above the road. */
  height: number;
  carriageway: number;
  lanes: number;
  oneway: boolean;
  edgeLines: boolean;
}

/** Buried networks. */
export type UtilityKind = 'gas' | 'water' | 'sewer' | 'power' | 'telecom' | 'heat';

/** A buried pipe / cable run. */
export interface Utility {
  id: string;
  /** Canonical city entity id (city_features.entity_id) when the object comes from the city model. */
  entity?: string;
  /** Source feature. */
  ref: string;
  kind: UtilityKind;
  /** Service connection to a building (not a main). */
  service: boolean;
  /** Outer diameter, m. */
  diameter: number;
  /** Centre line, absolute heights (below the surface by cover + radius). */
  path: Vec3[];
  material?: string;
  provenance: Provenance;
  /** Crossings where the compiler moved this run over / under another network. */
  rerouted?: number;
}

/** Access point of a buried network: a manhole / chamber or a valve. */
export interface UtilityNode {
  id: string;
  /** Canonical city entity id (city_features.entity_id) when the object comes from the city model. */
  entity?: string;
  ref: string;
  kind: UtilityKind;
  type: 'manhole' | 'valve';
  /** Cover on the surface. */
  position: Vec3;
  /** Shaft depth below the cover, m. */
  depth: number;
}

export interface CityModel {
  version: 1;
  name: string;
  /** Geographic position of model (0, 0). */
  origin: LonLat;
  /** Set when the model is one UTM tile. */
  frame?: TileFrameInput;
  bounds: { minX: number; minY: number; maxX: number; maxY: number };
  attribution: string[];
  terrain: TerrainGrid;
  roads: Road[];
  surfaces: Surface[];
  markings: Marking[];
  crossings: Crossing[];
  junctions: Junction[];
  bridges: Bridge[];
  /** Underpass trenches (retaining walls), tunnel portals and tubes. */
  cuttings: Cutting[];
  portals: Portal[];
  tunnels: Tunnel[];
  terrainCut?: TerrainCut;
  /** Garden walls, fences and hedges. */
  fences?: Fence[];
  /** Buried pipes and cables, and their manholes / valves. */
  utilities?: Utility[];
  utilityNodes?: UtilityNode[];
  /**
   * Street land outside the road corridors: gaps narrower than 3 m between two
   * sidewalks, drawn as sidewalk and levelled to the street surface (see
   * RoadSurface fill).
   */
  streetFill?: Polygon[];
  areas: Area[];
  blocks: CityBlock[];
  buildings: Building[];
  props: Prop[];
  fixes: Fix[];
  stats: Record<string, number>;
}

export interface CompileOptions {
  /** Terrain grid resolution in metres. */
  terrainCell?: number;
  /** Fill city blocks with synthetic buildings where source data has none. */
  infill?: boolean;
  /** Add synthetic street furniture (lamps, trees). */
  decorate?: boolean;
  /** Run planning analyses that emit `suggested` props. */
  suggest?: boolean;
}
