export interface CityBlock {
  id: string;
  polygon: Polygon;
  area: number;
  /** Road classes that bound the block (highest first). */
  frontage: RoadClass[];
  /** Share of block area covered by observed buildings. */
  observedCoverage: number;
  syntheticBuildings: number;
}

export type Archetype = 'mustakil' | 'eski' | 'klasik' | 'modern' | 'yuksek';
/** `barrel`: arched (segmental) roof over the top floor, 2010s blocks. */
export type RoofShape = 'hip' | 'gable' | 'flat' | 'barrel';
export type BayKind =
  /** Standard two-casement window. */
  | 'window'
  /** Three-casement living-room window, about twice as wide. */
  | 'wide-window'
  /** Two separate windows side by side with a pier between (ikili pencere). */
  | 'pair-window'
  /** Small single-casement window set high (bathroom, kitchen, stairs). */
  | 'small-window'
  /** Door-height window with a rail flush to the wall (Fransız balkon). */
  | 'french-window'
  /** Door-height two- / three-casement windows down to the floor. */
  | 'tall-pair'
  | 'tall-triple'
  | 'balcony'
  | 'glazed-balcony'
  | 'blank'
  | 'door'
  | 'shop'
  | 'garage';
export type RailKind = 'solid' | 'glass' | 'metal';
export type WallFinish = 'plaster' | 'cladding-wood' | 'cladding-panel' | 'stone' | 'brick';

export interface FacadeEdge {
  /** Index of the start vertex in footprint.outer; edge runs to the next vertex. */
  edge: number;
  length: number;
  /** Bays along the edge; empty for blank walls (party walls / short edges). */
  bays: BayKind[];
  groundBays: BayKind[];
  /** Per-bay wall finish index into Building.finishes (vertical colour bands). */
  bands: number[];
  front: boolean;
  /**
   * Cumba / çıkma: bays [from, to] project from the wall on the upper floors
   * (closed bay with windows), as on older Anatolian apartments.
   */
  oriel?: [number, number];
  /** Bay boundary (0…bays) carrying a full-height ornamental motif strip. */
  ornament?: number;
  /**
   * Single flats that differ from their column: [floor, bay, kind] (floor ≥ 1).
   * Residents glaze one balcony, open another, swap a window for a door …
   */
  cells?: [number, number, BayKind][];
}

/** What a building is used for (from the source tags): drives its facade rules. */
export type BuildingUse = 'residential' | 'house' | 'public' | 'commercial';

export interface BuildingPalette {
  wall: string;
  band: string;
  trim: string;
  roof: string;
  base: string;
  frame: string;
  glass: string;
}

export interface Building {
  id: string;
  osmId?: number;
  /** Stable source identity of observed buildings ("osm:w123", "maks:4711"). */
  ref?: string;
  /** Canonical city entity id (city_features.entity_id) when the object comes from the city model. */
  entity?: string;
  /** Source name ("osm", "maks", …) or "synthetic" for block infill. */
  source: string;
  /** Source table columns of observed buildings (MAKS …), by column name. */
  attrs?: Record<string, string>;
  /** Canonical id of the parcel the building stands on (tag `ref:parcel`). */
  parcelRef?: string;
  footprint: Polygon;
  area: number;
  /** Lowest terrain under the footprint (walls start here). */
  baseZ: number;
  /** Ground floor level; floor 0 starts here. */
  floorZ: number;
  /** Height of the ground floor above the street at the front door (steps up). */
  plinth: number;
  levels: number;
  floorHeight: number;
  groundFloorHeight: number;
  /** Top of the wall (eave / parapet base). */
  topZ: number;
  archetype: Archetype;
  palette: BuildingPalette;
  finishes: WallFinish[];
  roof: { shape: RoofShape; pitchDeg: number; overhang: number; parapet: number };
  rail: RailKind;
  windowWidth: number;
  windowHeight: number;
  shopfront: boolean;
  use: BuildingUse;
  facades: FacadeEdge[];
  /**
   * Corner balconies on the upper floors: edge indices k whose end corner
   * (shared with edge k+1, convex, near-square) carries an L-shaped balcony.
   */
  cornerBalconies: number[];
  provenance: { footprint: Provenance; levels: Provenance; style: Provenance };
  fixIds: string[];
  seed: number;
}

