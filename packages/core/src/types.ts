/**
 * City model contract produced by `compileCity` and consumed by renderers.
 *
 * Coordinates are local metres on a tangent plane around `origin`:
 * x = east, y = north, z = up (terrain / building heights). Renderers map
 * this to their own axes (three.js: x, z = -y, y = up).
 */

export type Vec2 = [number, number];
export type Vec3 = [number, number, number];

/** Polygon with an outer ring (CCW) and optional holes (CW). Rings are open (last != first). */
export interface Polygon {
  outer: Vec2[];
  holes: Vec2[][];
}

/**
 * Where a value came from:
 * - `observed`: present in the source data
 * - `inferred`: derived by a rule from observed evidence (e.g. crossing at a signalised junction)
 * - `synthetic`: generated only so the scene looks complete (decoration, block infill)
 * - `suggested`: generated by an analysis rule and meant as a planning hint (e.g. missing bus stop)
 */
export type Provenance = 'observed' | 'inferred' | 'synthetic' | 'suggested';

// ─── Source (input) ──────────────────────────────────────────────────────────

export interface LonLat {
  lon: number;
  lat: number;
}

/** Raw OSM element as stored in fixtures (Overpass `out geom`, compacted). */
export interface OsmElement {
  type: 'node' | 'way' | 'relation';
  id: number;
  tags: Record<string, string>;
  lon?: number;
  lat?: number;
  nodes?: number[];
  geometry?: [number, number][];
  members?: { ref: number; role: string; geometry: [number, number][] }[];
}

/** Terrain height grid in geographic coordinates, row 0 = north, pixel centres. */
export interface GeoTerrainGrid {
  source: string;
  west: number;
  east: number;
  north: number;
  south: number;
  cols: number;
  rows: number;
  heights: number[];
}

/** GeoJSON geometry (EPSG:4326) of a source-store feature. */
export interface SourceGeometry {
  type: 'Point' | 'LineString' | 'MultiLineString' | 'Polygon' | 'MultiPolygon';
  coordinates: unknown;
}

/** A canonical feature from the source store (OSM import, MAKS, platform layer…). */
export interface SourceFeatureInput {
  /** Stable identity, e.g. "osm:w123", "maks:4711". */
  ref: string;
  /** Short source name shown to users ("osm", "maks", …). */
  source: string;
  /** Higher wins: a building overrides lower-priority buildings it overlaps. */
  priority?: number;
  /**
   * The source is the complete building register where it has data (e.g. the
   * municipality's MAKS table): around its buildings no other source's
   * building and no procedural infill is placed.
   */
  authoritative?: boolean;
  kind: 'building' | 'road' | 'area' | 'point';
  geometry: SourceGeometry;
  tags: Record<string, string | number>;
}

/** Compile target: a 1 km UTM tile (see tiles.ts). */
export interface TileFrameInput {
  zone: number;
  originE: number;
  originN: number;
  size: number;
  margin: number;
}

export interface CitySource {
  name: string;
  /** [west, south, east, north] — the area to compile when no `frame` is given. */
  bbox: [number, number, number, number];
  attribution: string[];
  osm?: OsmElement[];
  features?: SourceFeatureInput[];
  terrain?: GeoTerrainGrid;
  /** Compile exactly this tile (model coords = UTM − origin); `bbox` is then ignored. */
  frame?: TileFrameInput;
}

// ─── Model (output) ──────────────────────────────────────────────────────────

/** Terrain resampled to a local metric grid (row 0 = south, i.e. minY). */
export interface TerrainGrid {
  minX: number;
  minY: number;
  cellSize: number;
  cols: number;
  rows: number;
  /** Row-major heights, conformed to the road network. */
  heights: number[];
  /** Height at or below which the ground is sea. */
  seaLevel: number;
}

export type RoadClass =
  | 'motorway'
  | 'trunk'
  | 'primary'
  | 'secondary'
  | 'tertiary'
  | 'residential'
  | 'unclassified'
  | 'living_street'
  | 'pedestrian'
  | 'service'
  | 'footway'
  | 'steps'
  | 'track'
  | 'cycleway';

export type Grade = 'ground' | 'bridge' | 'tunnel';

export interface Road {
  id: string;
  /** Stable source identity ("osm:w123"). */
  ref: string;
  osmId?: number;
  name?: string;
  cls: RoadClass;
  grade: Grade;
  layer: number;
  centerline: Vec2[];
  /** Carriageway (or path) width in metres. */
  width: number;
  sidewalk: number;
  lanes: number;
  oneway: boolean;
  /** Road bounds city blocks (vehicular / pedestrian street at ground level). */
  formsBlocks: boolean;
  provenance: { width: Provenance; lanes: Provenance };
}

export type MarkingKind = 'center-dashed' | 'center-solid' | 'lane-dashed' | 'edge' | 'stop';

export interface Marking {
  kind: MarkingKind;
  points: Vec2[];
}

export interface Crossing {
  id: string;
  center: Vec2;
  /** Unit vector along the road (stripes run across it). */
  dir: Vec2;
  /** Distance across the road. */
  length: number;
  provenance: Provenance;
}

export interface Junction {
  id: string;
  center: Vec2;
  radius: number;
  roadIds: string[];
  signalised: boolean;
}

export type SurfaceKind = 'asphalt' | 'paving' | 'sidewalk' | 'path' | 'island' | 'yard';

export interface Surface {
  kind: SurfaceKind;
  polygons: Polygon[];
}

export type AreaKind =
  | 'park'
  | 'grass'
  | 'forest'
  | 'water'
  | 'parking'
  | 'plaza'
  | 'school'
  | 'religious'
  | 'industrial'
  | 'residential';

export interface Area {
  id: string;
  kind: AreaKind;
  polygon: Polygon;
  provenance: Provenance;
}

export interface CityBlock {
  id: string;
  polygon: Polygon;
  area: number;
  /** Road classes that bound the block (highest first). */
  frontage: RoadClass[];
  /** Share of block area covered by observed buildings. */
  observedCoverage: number;
  syntheticBuildings: number;
}

export type Archetype = 'mustakil' | 'eski' | 'klasik' | 'modern' | 'yuksek';
export type RoofShape = 'hip' | 'gable' | 'flat';
export type BayKind =
  | 'window'
  | 'balcony'
  | 'glazed-balcony'
  | 'blank'
  | 'door'
  | 'shop'
  | 'garage';
export type RailKind = 'solid' | 'glass' | 'metal';
export type WallFinish = 'plaster' | 'cladding-wood' | 'cladding-panel' | 'stone' | 'brick';

export interface FacadeEdge {
  /** Index of the start vertex in footprint.outer; edge runs to the next vertex. */
  edge: number;
  length: number;
  /** Bays along the edge; empty for blank walls (party walls / short edges). */
  bays: BayKind[];
  groundBays: BayKind[];
  /** Per-bay wall finish index into Building.finishes (vertical colour bands). */
  bands: number[];
  front: boolean;
}

export interface BuildingPalette {
  wall: string;
  band: string;
  trim: string;
  roof: string;
  base: string;
  frame: string;
  glass: string;
}

export interface Building {
  id: string;
  osmId?: number;
  /** Stable source identity of observed buildings ("osm:w123", "maks:4711"). */
  ref?: string;
  /** Source name ("osm", "maks", …) or "synthetic" for block infill. */
  source: string;
  /** Source table columns of observed buildings (MAKS …), by column name. */
  attrs?: Record<string, string>;
  /** Canonical id of the parcel the building stands on (tag `ref:parcel`). */
  parcelRef?: string;
  footprint: Polygon;
  area: number;
  /** Lowest terrain under the footprint (walls start here). */
  baseZ: number;
  /** Street level at the front edge; floor 0 starts here. */
  floorZ: number;
  levels: number;
  floorHeight: number;
  groundFloorHeight: number;
  /** Top of the wall (eave / parapet base). */
  topZ: number;
  archetype: Archetype;
  palette: BuildingPalette;
  finishes: WallFinish[];
  roof: { shape: RoofShape; pitchDeg: number; overhang: number; parapet: number };
  rail: RailKind;
  windowWidth: number;
  windowHeight: number;
  shopfront: boolean;
  facades: FacadeEdge[];
  provenance: { footprint: Provenance; levels: Provenance; style: Provenance };
  fixIds: string[];
  seed: number;
}

export type PropKind =
  | 'tree'
  | 'street-lamp'
  | 'traffic-signal'
  | 'bus-stop'
  | 'bench'
  | 'waste-basket'
  | 'power-pole'
  | 'chimney'
  | 'solar-heater'
  | 'satellite-dish'
  | 'ac-unit';

export interface Prop {
  id: string;
  kind: PropKind;
  position: Vec3;
  /** Heading in radians (0 = +x, CCW). */
  heading: number;
  scale: number;
  provenance: Provenance;
  /** Human readable reason for inferred / suggested props. */
  reason?: string;
  buildingId?: string;
}

export type FixKind = 'road-overlap' | 'building-overlap' | 'invalid-geometry' | 'sliver';

export interface Fix {
  id: string;
  kind: FixKind;
  targetId: string;
  /** Area removed from the source geometry, m². */
  removedArea: number;
  /** Removed parts, for highlighting. */
  removed: Polygon[];
  /** Height to extrude the highlight to (the building height). */
  height: number;
  baseZ: number;
  note: string;
}

export interface Bridge {
  id: string;
  roadId: string;
  /** Deck centreline with deck-top heights. */
  path: Vec3[];
  width: number;
}

export interface CityModel {
  version: 1;
  name: string;
  /** Geographic position of model (0, 0). */
  origin: LonLat;
  /** Set when the model is one UTM tile. */
  frame?: TileFrameInput;
  bounds: { minX: number; minY: number; maxX: number; maxY: number };
  attribution: string[];
  terrain: TerrainGrid;
  roads: Road[];
  surfaces: Surface[];
  markings: Marking[];
  crossings: Crossing[];
  junctions: Junction[];
  bridges: Bridge[];
  areas: Area[];
  blocks: CityBlock[];
  buildings: Building[];
  props: Prop[];
  fixes: Fix[];
  stats: Record<string, number>;
}

export interface CompileOptions {
  /** Terrain grid resolution in metres. */
  terrainCell?: number;
  /** Fill city blocks with synthetic buildings where source data has none. */
  infill?: boolean;
  /** Add synthetic street furniture (lamps, trees). */
  decorate?: boolean;
  /** Run planning analyses that emit `suggested` props. */
  suggest?: boolean;
}
